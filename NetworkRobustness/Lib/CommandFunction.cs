                                break;
                        }
                        break;
                    case 1:// K-CORE method selected
                        switch (kCore)
                        {
                            case 1:
                                //<---K-shell with peripheral removal
                                User.One.MessageToUser("K-shell detects the core without peripheral!");
                                shellcentrality = onet.K_ShellCentrality();
                                coreNode = from p in shellcentrality where p.Value > 1 select p.Key;
                                break;
                            case 2:
                                //<--K-shell with 2-core--
                                User.One.MessageToUser("K-shell detects the second-innermost core!");
                                shellcentrality = onet.K_ShellCentrality();
                                int border0 = shellcentrality.Values.Max();
                                int border1 = (from p in shellcentrality.Values where p < border0 select p).Max();
                                coreNode = from p in shellcentrality where p.Value >= border1 select p.Key;
                                break;
                            case 3:
                                //<--K-shell with 1 innermost core--
                                User.One.MessageToUser("K-shell detects the innermost core!");
                                shellcentrality = onet.K_ShellCentrality();
                                coreNode = from p in shellcentrality where p.Value == shellcentrality.Values.Max() select p.Key;
                                break;
                            default:
                                User.One.SendErrorToUser(new Exception("Select not correct parameter k-core = {1,2,}!"));
                                break;
                        }
                        break;
                    default:
                        User.One.SendErrorToUser(new Exception("Not selecting right core method!"));
                        break;
                }

                //var coreNode = from p in kReachingcentrality where p.Value == kReachingcentrality.Values.Max() select p.Key;
