                            Mo.ToString(), Ro.ToString(),inRo.ToString(),outRo.ToString(),
                            inGamma.ToString(),inR.ToString(),inPvalue.ToString(),outGamma.ToString(),outR.ToString(),outPvalue.ToString()
                        };
                // "In-power law", "In-R", "In-Pvalue", "Out-power law","Out-R","Out-Pvalue"
                TextDB.WriteTextFile(f, ReportFileName);


            }
            User.One.MessageToUser("The result is saved at" + ReportFileName);
