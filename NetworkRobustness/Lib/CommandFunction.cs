            int num_nets = Convert.ToInt32(Parameter[0].Value);
            int nodeFrom = Convert.ToInt32(Parameter[1].Value);
            int nodeTo = Convert.ToInt32(Parameter[2].Value);

            double averagek = Convert.ToDouble(Parameter[3].Value);
