                    continue;



                BooleanNetwork net = onet.CreateNewSortestConnectionSubnetwork(coreNode) as BooleanNetwork;
                //BooleanNetwork net = onet.CreateNewExtractedSubnetwork(coreNode) as BooleanNetwork;
                net.WriteToFile("core_" + Netutil.ExtractFileNameFromPath(fileName));

