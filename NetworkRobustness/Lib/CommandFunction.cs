        private static void OnNetworkRewireCommand(Dictionary<int, KeyValuePair<string, object>> Parameter)
        {
            string fileName = Convert.ToString(Parameter[0].Value);
            int nNet = Convert.ToInt32(Parameter[1].Value);
            float fromRate = Convert.ToSingle(Parameter[2].Value);
            float toRate = Convert.ToSingle(Parameter[3].Value);
            bool calMo = Convert.ToBoolean(Parameter[4].Value);
            bool calRo = Convert.ToBoolean(Parameter[5].Value);
           
            string MoRoName = fileName.Substring(0, fileName.LastIndexOf('.')) + ".RoMo.txt";
            BooleanNetwork net = BooleanNetwork.ReadSignalingNetworkFile(fileName);
            User.One.MessageToUser("File \"" + fileName + "\" has been load successfully!\nBegin rewiring this file");


            TextDB.WriteTextFile(string.Format("{0}\t{1}\t{2}", "File", "Robustness", "Directed weighted Modularity"), MoRoName);
         
         
            double Ro = -1;
            double Mo = -1;
            for (int i = 0; i < nNet; i++)
            {
                User.One.ShowWaitIndicator(i , nNet);
                double al = Math.Round(fromRate + (toRate - fromRate) * Mathutil.NumericMath.RandomCraft.NextDouble(), 3);

                string rewiredFile = fileName.Substring(0, fileName.LastIndexOf('.')) + ".Rewire." + al.ToString() + ".txt";
                if (TextDB.Exists(rewiredFile))
                {
                    i--;
                    continue;
                }
                User.One.MessageToUser("Shuffling...");
                BooleanNetwork perturbNetwork = net.ShufflePreservingDegree((int)(al * net.Arcs.Count()), true) as BooleanNetwork;

                perturbNetwork.WriteToFile(rewiredFile);
                User.One.MessageToUser("Saved rewired file! "+rewiredFile);
                if (calMo)
                {
                    User.One.MessageToUser("Calculating modularity on file:"  + rewiredFile);
                    Dictionary<Node, int> pCluster = null;
                    Mo = perturbNetwork.modularityWeightedDirected(ref pCluster);
                }
                if (calRo)
                {
                    User.One.MessageToUser("Calculating robustness on file:" + rewiredFile);
                    Ro = perturbNetwork.NetworkMutantRobustnessParalell();
                }


                User.One.MessageToUser("Summarizing to file:" + MoRoName);
                TextDB.WriteTextFile(string.Format("{0}\t{1}\t{2}", rewiredFile, Ro, Mo), MoRoName);
                
                
            }
        }

